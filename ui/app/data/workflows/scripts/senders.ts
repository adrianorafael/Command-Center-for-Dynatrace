/**
 * Per-channel sender task sources (workflow "Run JavaScript" tasks send_*).
 *
 * Vendor API references (read 2026-11-26):
 *  - Twilio Messages: POST https://api.twilio.com/2010-04-01/Accounts/{AccountSid}/Messages.json,
 *    application/x-www-form-urlencoded, To + From|MessagingServiceSid + Body, HTTP Basic auth,
 *    response `sid` — https://www.twilio.com/docs/messaging/api/message-resource
 *  - Twilio WhatsApp: same endpoint, To/From prefixed `whatsapp:` (approved sender) — same page
 *  - Twilio Calls: POST …/Accounts/{AccountSid}/Calls.json, To + From + Twiml
 *    ("<Response><Say>…</Say></Response>"), response `sid` — https://www.twilio.com/docs/voice/api/call-resource
 *  - IFTTT Webhooks: POST https://maker.ifttt.com/trigger/{event}/with/key/{key} with JSON
 *    value1..value3 — IFTTT help center "What is the Webhooks service?" (via web search; page fetch
 *    returned 403) → treat as VERIFIED-SECONDARY
 *  - Slack incoming webhook: POST https://hooks.slack.com/services/…, application/json, {text, blocks},
 *    200 + plain "ok" — https://docs.slack.dev/messaging/sending-messages-using-incoming-webhooks
 *  - Microsoft Teams: Office 365 connector webhooks were retired (May 2026); use a Teams Workflows
 *    "When a Teams webhook request is received" webhook, which accepts Adaptive Card payloads
 *    {type:"message", attachments:[{contentType:"application/vnd.microsoft.card.adaptive", content}]},
 *    28 KB limit — https://learn.microsoft.com/microsoftteams/platform/webhooks-and-connectors/how-to/add-incoming-webhook
 *    The webhook host depends on the tenant's Power Automate environment (copy it from the URL).
 *  - Telegram Bot API: https://api.telegram.org/bot<token>/sendMessage, chat_id, text (1-4096 chars),
 *    link_preview_options; response {ok, result: Message{message_id}} — https://core.telegram.org/bots/api#sendmessage
 *
 * Credential mapping (Credential Vault entry referenced by ProviderConfig.credentialVaultId):
 *  - twilio:        USERNAME_PASSWORD — user = Account SID or API Key SID, password = Auth Token / API secret;
 *                   params.accountSid (needed when user is an API Key SID), params.from, params.messagingServiceSid,
 *                   params.voice, params.language
 *  - ifttt:         TOKEN = Webhooks key; params.event
 *  - slack-webhook: TOKEN = full incoming-webhook URL
 *  - teams-webhook: TOKEN = full Teams Workflows webhook URL
 *  - telegram-bot:  TOKEN = bot token; to.address = chat id
 *  - webhook:       TOKEN = full https URL; optional params.authHeader + password from a USERNAME_PASSWORD entry
 */

import type { Channel } from "../../../domain/contracts";
import { IMPORT_RESULT, IMPORT_VAULT, SENDER_RUNTIME } from "./common";

function senderScript(channel: Channel, title: string, sendFn: string): string {
  return `// Command Center · ${title} — generated by ui/app/data/workflows/scripts/senders.ts. Do not edit in the workflow.
${IMPORT_RESULT}
${IMPORT_VAULT}
${SENDER_RUNTIME}
${sendFn}

export default async function () {
  return runChannel(${JSON.stringify(channel)}, send);
}
`;
}

const TWILIO_HELPERS = `
function twilioAuth(cred) {
  if (!cred.user || !cred.password) throw new Error("Twilio credential needs username (SID) and password (token)");
  return "Basic " + btoa(cred.user + ":" + cred.password);
}

function twilioAccount(provider, cred) {
  var sid = (provider.params && provider.params.accountSid) || cred.user;
  if (!/^AC[0-9a-fA-F]{32}$/.test(sid || "")) throw new Error("Twilio account SID missing or malformed (params.accountSid)");
  return sid;
}

async function twilioPost(provider, cred, resource, form) {
  var url = "https://api.twilio.com/2010-04-01/Accounts/" + twilioAccount(provider, cred) + "/" + resource + ".json";
  var res = await post(url, {
    headers: { "Authorization": twilioAuth(cred), "Content-Type": "application/x-www-form-urlencoded" },
    body: new URLSearchParams(form).toString(),
  });
  if (!res.ok) throw await httpError(res);
  var json = await res.json();
  return json && json.sid;
}

function twilioSender(provider, prefix) {
  var p = provider.params || {};
  if (p.messagingServiceSid && !prefix) return { MessagingServiceSid: p.messagingServiceSid };
  if (!p.from) throw new Error("Twilio provider needs params.from");
  return { From: prefix && p.from.indexOf(prefix) !== 0 ? prefix + p.from : p.from };
}
`;

export const SEND_TWILIO_SMS = senderScript(
  "sms",
  "Twilio SMS",
  `${TWILIO_HELPERS}
async function send(n, provider, cred) {
  var form = Object.assign({ To: n.to.address, Body: n.text.slice(0, 1600) }, twilioSender(provider, ""));
  return twilioPost(provider, cred, "Messages", form);
}`,
);

