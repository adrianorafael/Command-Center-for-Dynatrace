export const SEND_TWILIO_VOICE = senderScript(
  "voice",
  "Twilio voice call",
  `${TWILIO_HELPERS}
function xmlEscape(s) {
  return String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;").replace(/'/g, "&apos;");
}

async function send(n, provider, cred) {
  var p = provider.params || {};
  var attrs = "";
  if (p.voice && /^[A-Za-z0-9._-]{1,60}$/.test(p.voice)) attrs += ' voice="' + p.voice + '"';
  if (p.language && /^[A-Za-z]{2,3}(-[A-Za-z0-9]{2,8})?$/.test(p.language)) attrs += ' language="' + p.language + '"';
  var say = xmlEscape((n.speech || n.text).slice(0, 1000));
  var twiml = "<Response><Say" + attrs + ">" + say + "</Say><Pause length=\\"1\\"/><Say" + attrs + ">" + say + "</Say></Response>";
  var form = Object.assign({ To: n.to.address, Twiml: twiml }, twilioSender(provider, ""));
  if (form.MessagingServiceSid) throw new Error("Twilio voice needs params.from (a voice-capable number)");
  return twilioPost(provider, cred, "Calls", form);
}`,
);

export const SEND_IFTTT = senderScript(
  "ifttt",
  "IFTTT webhook",
  `
async function send(n, provider, cred) {
  var event = (provider.params && provider.params.event) || "";
  if (!/^[A-Za-z0-9_-]{1,100}$/.test(event)) throw new Error("IFTTT provider needs params.event ([A-Za-z0-9_-])");
  if (!cred.token) throw new Error("IFTTT credential needs a token (Webhooks key)");
  var url = "https://maker.ifttt.com/trigger/" + event + "/with/key/" + encodeURIComponent(cred.token);
  var res = await post(url, {
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({ value1: n.subject, value2: n.text, value3: n.incidentUrl }),
  });
  if (!res.ok) throw await httpError(res);
  return undefined;
}`,
);

export const SEND_SLACK = senderScript(
  "slack",
  "Slack incoming webhook",
  `
async function send(n, provider, cred) {
  var url = cred.token || "";
  if (url.indexOf("https://hooks.slack.com/") !== 0) throw new Error("Slack credential must hold an https://hooks.slack.com/ webhook URL");
  var who = forUser(n);
  var text = (who ? who + ": " : "") + n.text;
  var res = await post(url, {
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({
      text: text.slice(0, 3000),
      blocks: [
        { type: "section", text: { type: "mrkdwn", text: ("*" + n.subject + "*\\n" + text).slice(0, 3000) } },
        { type: "context", elements: [{ type: "mrkdwn", text: ("<" + n.incidentUrl + "|Open in Command Center> · " + n.priority).slice(0, 300) }] },
      ],
    }),
  });
  if (!res.ok) throw await httpError(res);
  return undefined;
}`,
);

export const SEND_TEAMS = senderScript(
  "teams",
  "Microsoft Teams workflow webhook",
  `
async function send(n, provider, cred) {
  var url = cred.token || "";
  if (url.indexOf("https://") !== 0) throw new Error("Teams credential must hold an https webhook URL");
  var who = forUser(n);
  var card = {
    type: "AdaptiveCard",
    $schema: "http://adaptivecards.io/schemas/adaptive-card.json",
    version: "1.4",
    body: [
      { type: "TextBlock", text: n.subject.slice(0, 300), weight: "Bolder", size: "Medium", wrap: true },
      { type: "TextBlock", text: ((who ? who + ": " : "") + n.text).slice(0, 4000), wrap: true },
    ],
    actions: [{ type: "Action.OpenUrl", title: "Open in Command Center", url: n.incidentUrl }],
  };
  var res = await post(url, {
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({ type: "message", attachments: [{ contentType: "application/vnd.microsoft.card.adaptive", contentUrl: null, content: card }] }),
  });
  if (!res.ok) throw await httpError(res);
  return undefined;
}`,
);

export const SEND_TELEGRAM = senderScript(
  "telegram",
  "Telegram bot",
  `
async function send(n, provider, cred) {
  if (!cred.token) throw new Error("Telegram credential needs a token (bot token)");
  var url = "https://api.telegram.org/bot" + cred.token + "/sendMessage";
  var res = await post(url, {
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({
      chat_id: n.to.address,
      text: (n.subject + "\\n" + n.text + "\\n" + n.incidentUrl).slice(0, 4096),
      link_preview_options: { is_disabled: true },
    }),
  });
  var json = null;
  try { json = await res.json(); } catch (e) { json = null; }
  if (!res.ok || !json || json.ok !== true) {
    throw new Error("HTTP " + res.status + (json && json.description ? ": " + String(json.description).slice(0, 200) : ""));
  }
  return json.result && json.result.message_id;
}`,
);

export const SEND_WEBHOOK = senderScript(
  "webhook",
  "generic webhook",
  `
async function send(n, provider, cred) {
  var url = cred.token || "";
  if (url.indexOf("https://") !== 0) throw new Error("Webhook credential must hold an https URL");
  var headers = { "Content-Type": "application/json" };
  var h = provider.params && provider.params.authHeader;
  if (h && /^[A-Za-z0-9-]{1,60}$/.test(h) && cred.password) headers[h] = cred.password;
  var res = await post(url, {
    headers: headers,
    body: JSON.stringify({ source: "command-center", version: 1, notification: n }),
  });
  if (!res.ok) throw await httpError(res);
  return res.headers.get("x-request-id") || undefined;
}`,
);

