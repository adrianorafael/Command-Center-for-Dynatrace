/**
 * `tick` and `report` task sources. Both call this app's functions with a relative URL
 * ("/apps/<appId>/api/<fn>"), which the workflow runtime authenticates automatically
 * (developer.dynatrace.com/develop/guides/workflows/automate-app-function-runs/ — spec H1;
 * relative-URL auth VERIFIED live on a trial tenant 2026-11-26).
 */

import { IMPORT_EXECUTION, IMPORT_RESULT } from "./common";
import { SENDER_TASKS } from "./senders";

const APP_ID_RE = /^[a-z][a-z0-9.-]{1,99}$/;

function checkAppId(appId: string): string {
  if (!APP_ID_RE.test(appId)) throw new Error(`Invalid app id: ${appId.slice(0, 60)}`);
  return appId;
}

/**
 * tick: forwards execution params (`reason`, optional `testRequest`) to engine-tick and returns
 * its response ({ ok, tickAt, batches, counts, errors, providers }) for the send_* tasks.
 */
export function tickScript(appId: string): string {
  return `// Command Center · tick — generated by ui/app/data/workflows/scripts/engine.ts. Do not edit in the workflow.
${IMPORT_EXECUTION}

var APP_ID = ${JSON.stringify(checkAppId(appId))};
var REASONS = ["schedule", "manual", "problem-trigger", "test"];

export default async function () {
  var ex = await execution();
  var params = (ex && ex.params) || {};
  var reason = REASONS.indexOf(params.reason) >= 0 ? params.reason
    : ex && ex.triggerType === "Schedule" ? "schedule"
    : ex && ex.triggerType === "Event" ? "problem-trigger"
    : "manual";
  var body = { reason: reason };
  if (reason === "test" && params.testRequest) body.testRequest = params.testRequest;
  var res = await fetch("/apps/" + APP_ID + "/api/engine-tick", {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify(body),
    signal: AbortSignal.timeout(110000),
  });
  if (!res.ok) {
    var detail = "";
    try { detail = (await res.text()).slice(0, 300); } catch (e) { detail = ""; }
    throw new Error("engine-tick failed: HTTP " + res.status + (detail ? " " + detail : ""));
  }
  return await res.json();
}
`;
}

/** report: collects every sender's DeliveryResult[] and posts them to delivery-report. */
export function reportScript(appId: string): string {
  return `// Command Center · report — generated by ui/app/data/workflows/scripts/engine.ts. Do not edit in the workflow.
${IMPORT_RESULT}

var APP_ID = ${JSON.stringify(checkAppId(appId))};
var SENDERS = ${JSON.stringify(SENDER_TASKS.map((t) => t.name))};

export default async function () {
  var all = [];
  var missing = [];
  for (var i = 0; i < SENDERS.length; i++) {
    try {
      var r = await result(SENDERS[i]);
      if (r && Array.isArray(r.results)) all = all.concat(r.results);
    } catch (e) {
      // Skipped or failed sender: its items stay "planned", time out and are retried by the engine.
      missing.push(SENDERS[i]);
    }
  }
  if (!all.length) return { reported: 0, missing: missing };
  var res = await fetch("/apps/" + APP_ID + "/api/delivery-report", {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({ results: all }),
    signal: AbortSignal.timeout(60000),
  });
  if (!res.ok) throw new Error("delivery-report failed: HTTP " + res.status);
  var out = await res.json();
  return { reported: all.length, missing: missing, applied: out && out.applied, unknown: out && out.unknown };
}
`;
}
